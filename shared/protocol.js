// Протокол реального времени (WebSocket): версия, коды закрытия соединения, политика переподключения.
// Общий код клиента и сервера.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.Protocol = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const VERSION = 1;

  // Коды закрытия соединения (4000–4999 — коды приложения)
  const CLOSE = {
    NORMAL: 1000, // игрок вышел сам
    PROTOCOL: 4000, // нарушение протокола / нет приветствия
    AUTH: 4001, // сессия недействительна (выход, истёк срок)
    BANNED: 4003, // аккаунт заблокирован
    FULL: 4004, // в мире нет мест
    REPLACED: 4005, // этот аккаунт вошёл в игру из другой вкладки / с другого устройства
    NO_ACCESS: 4006, // нет доступа к миру (закрыт, удалён, персонаж не найден)
    HOST_OFFLINE: 4008, // владелец мира не в игре (настройка game.requireOwnerOnline)
    KICKED: 4009, // отключён администратором
    SHUTDOWN: 4010, // сервер перезапускается
  };

  const CLOSE_TEXT = {
    1000: 'Вы вышли из мира.',
    4000: 'Ошибка протокола связи с сервером.',
    4001: 'Сессия недействительна — войдите в игру снова.',
    4003: 'Аккаунт заблокирован.',
    4004: 'В мире нет свободных мест.',
    4005: 'Вы вошли в игру в другой вкладке или на другом устройстве.',
    4006: 'Нет доступа к миру.',
    4008: 'Владелец мира сейчас не в игре.',
    4009: 'Вы отключены администратором.',
    4010: 'Сервер перезапускается.',
  };

  // После этих кодов переподключаться бессмысленно
  const FINAL = new Set([1000, 4000, 4001, 4003, 4004, 4005, 4006, 4008, 4009]);
  const shouldReconnect = (code) => !FINAL.has(code);

  // Задержка перед попыткой переподключения: экспонента с потолком (attempt с 0).
  // rnd — случайное число 0..1 для разброса ±25% (чтобы клиенты не переподключались одновременно)
  function backoffDelay(attempt, baseMs, maxMs, rnd) {
    const d = Math.min(maxMs, baseMs * Math.pow(2, Math.max(0, attempt)));
    return rnd === undefined ? d : Math.round(d * (0.75 + rnd * 0.5));
  }

  return { VERSION, CLOSE, CLOSE_TEXT, shouldReconnect, backoffDelay };
});
